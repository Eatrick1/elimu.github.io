// SCROLL FADE BACKGROUNDS (Watoto-style)
// ==========================================
(function initScrollFadeBackgrounds() {
  var sections = document.querySelectorAll('.fade-scroll-bg');
  if (!sections.length) return;

  var items = [];
  sections.forEach(function(sec) {
    var targetSel = sec.getAttribute('data-fade-target');
    var layer = targetSel ? sec.querySelector(targetSel) : null;
    if (layer) items.push({ sec: sec, layer: layer });
  });
  if (!items.length) return;

  var ticking = false;

  function update() {
    var vh = window.innerHeight;
    items.forEach(function(item) {
      var rect = item.sec.getBoundingClientRect();
      // Fade out as the section's top scrolls above the viewport top.
      // Fully visible while rect.top >= 0; fades to 0 opacity over 70% of viewport height of upward scroll.
      var range = vh * 0.7;
      var progress = Math.min(Math.max((-rect.top) / range, 0), 1);
      item.layer.style.opacity = 1 - progress;
    });
    ticking = false;
  }

  function onScroll() {
    if (!ticking) {
      window.requestAnimationFrame(update);
      ticking = true;
    }
  }

  window.addEventListener('scroll', onScroll, { passive: true });
  window.addEventListener('resize', onScroll);
  update();
})();

